async function seed() {
  console.log("بدء البذر…");

  await db.insert(authors).values(
    WRITERS.map((w) => ({ name: w.name, role: w.role, initials: w.initials, bio: w.bio })),
  );

  await db.insert(categories).values(
    SECTIONS.map((s) => ({
      name: s.name, slug: s.slug, description: s.description,
      sortOrder: s.sortOrder, cover: s.cover, isActive: true,
    })),
  );

  await db.insert(tags).values(
    TOPICS.map((t) => ({ name: t.name, slug: t.slug, description: t.description })),
  );

  const sectionId = new Map(SECTIONS.map((s, i) => [s.slug, i + 1]));
  const topicId = new Map(TOPICS.map((t, i) => [t.slug, i + 1]));

  await db.insert(articles).values(
    ARTICLES.map((a) => ({
      title: a.title,
      slug: a.slug,
      excerpt: a.excerpt,
      content: a.content,
      cover: a.cover,
      status: "published" as const,
      isBreaking: a.breaking ?? false,
      isFeatured: a.featured ?? false,
      viewsCount: a.views,
      publishedAt: hoursAgo(a.hours),
      authorId: a.author,
      categoryId: sectionId.get(a.section)!,
    })),
  );

  const links = ARTICLES.flatMap((a, i) =>
    a.topics.map((t) => ({ articleId: i + 1, tagId: topicId.get(t)! })),
  );
  await db.insert(articleTags).values(links);

  console.log(
    `تمّ: ${ARTICLES.length} مقالاً · ${SECTIONS.length} قسماً · ${TOPICS.length} محوراً · ${WRITERS.length} كتّاب · ${links.length} ربطاً`,
  );
  process.exit(0);
}

